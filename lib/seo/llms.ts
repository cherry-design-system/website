import { faqs, features } from "@/lib/content";
import { absoluteUrl, site } from "@/lib/site";

const summary = `> ${site.description}`;

/** llms.txt: a short index for AI agents (https://llmstxt.org). */
export function llmsIndex() {
  return [
    `# ${site.fullName}`,
    "",
    summary,
    "",
    `Install: \`${site.installCommand}\``,
    "",
    "## Pages",
    "",
    `- [Home](${absoluteUrl("/")}): ${site.tagline} Overview, live components and install.`,
    "",
    "## Full content for LLMs",
    "",
    `- [llms-full.txt](${absoluteUrl("/llms-full.txt")}): the whole site as Markdown, with setup and usage.`,
    "",
    "## Developer resources",
    "",
    `- [Playground](${site.links.playground}): every cherry component, live, in light and dark.`,
    `- [Source code](${site.links.github}): components, tokens and the agent skill.`,
    `- [npm package](${site.links.npm}): ${site.packageName}.`,
    `- [Releases](${site.links.releases}): changelog.`,
    `- [Issues](${site.links.githubIssues}): bug reports and feature requests.`,
    `- Agent skill: \`npx -y skills add cherry-design-system/react\` teaches coding agents the components, props and tokens.`,
    "",
  ].join("\n");
}

/** llms-full.txt: the page content in Markdown, for agents that do not run JS. */
export function llmsFull() {
  return [
    `# ${site.fullName} ${site.version}`,
    "",
    summary,
    "",
    `## ${site.tagline}`,
    "",
    site.shortDescription,
    "",
    "## Install",
    "",
    "```bash",
    site.installCommand,
    "```",
    "",
    "## Set up (Next.js App Router)",
    "",
    "```tsx",
    "// app/layout.tsx",
    'import "@cherry-design-system/react/styles.css";',
    'import { themeInitScript } from "@cherry-design-system/react/theme-init";',
    "",
    "export default function RootLayout({ children }: { children: React.ReactNode }) {",
    "  return (",
    '    <html lang="en" suppressHydrationWarning>',
    "      <head>",
    "        <script dangerouslySetInnerHTML={{ __html: themeInitScript }} />",
    "      </head>",
    '      <body className="cherry-root">{children}</body>',
    "    </html>",
    "  );",
    "}",
    "```",
    "",
    "```tsx",
    'import { Button, ThemeToggle } from "@cherry-design-system/react";',
    "",
    '<Button variant="outline">Learn more</Button>',
    "<ThemeToggle />",
    "```",
    "",
    "## Why cherry",
    "",
    ...features.map((f) => `- **${f.title}.** ${f.description}`),
    "",
    "## How it works",
    "",
    "- **Static CSS.** Every rule lives in `@layer cherry`, so any unlayered rule of yours wins without `!important`.",
    "- **Stable hooks.** Classes are `cherry-<name>`, variants are `data-*` attributes, tokens are `--cherry-*` custom properties.",
    "- **Modes.** The `dark` class on `<html>` switches every token with no re-render. Scope a section with `data-cherry-mode`.",
    '- **Brands.** `createBrand("acme", { accent: "#5b5bd6" })` returns validated CSS for a `[data-cherry-brand="acme"]` scope.',
    "- **Motion.** Durations and easings are tokens, and every animation honours `prefers-reduced-motion`.",
    "",
    "## Components",
    "",
    "More than 60 components, light and dark, accessible by default:",
    "",
    "- Actions: Button, IconButton, ConfirmButton, Link",
    "- Forms: Field, Input, Textarea, Select, Combobox, Password, NumberField, OTPInput, Checkbox, RadioGroup, Radio, Toggle, Range, ToggleGroup, ThemeToggle, Tag, Dropzone, FileItem, AvatarDropzone",
    "- Pickers: Calendar, DatePicker, TimePicker, DateTimePicker",
    "- Navigation: Tabs, Sidebar, NavPill, Breadcrumb, Pagination, Stepper",
    "- Overlays: Menu, Modal, Sheet, Popover, Tooltip, SearchDialog",
    "- Feedback: Toast, Banner, Callout, Progress, Spinner, Skeleton, EmptyState",
    "- Data display: Badge, Avatar, AvatarGroup, Table, StatCard, Kbd",
    "- Content: Card, Accordion, Prose, CodeBlock, InlineCode, Snippet, Separator",
    "- Layout: Container, Grid, Col, Flex, Stack",
    "- AI chat kit: ChatPanel, ChatMessageList, ChatMessage, ChatInput, ChatLauncher, ChatTyping, ChatSources, ChatSuggestions",
    "",
    "## FAQ",
    "",
    ...faqs.flatMap((f) => [`### ${f.question}`, "", f.answer, ""]),
    "## Links",
    "",
    `- Website: ${site.url}`,
    `- Source: ${site.links.github}`,
    `- npm: ${site.links.npm}`,
    `- License: ${site.license}`,
    "",
  ].join("\n");
}
